"""Generate README.md from the curated agent-skills registry."""

from __future__ import annotations

from collections import defaultdict

from __version__ import __version__
from data import TOOLS, Category, Tool


def _badge(label: str, message: str, color: str) -> str:
    label = label.replace(" ", "%20")
    message = str(message).replace(" ", "%20").replace("-", "--")
    return f"![{label}](https://img.shields.io/badge/{label}-{message}-{color})"


def _source(t: Tool) -> str:
    if t.open_source:
        return "🟢 OSS"
    if t.license != "Proprietary":
        return "🔃 Source-available"
    return "🔒 Proprietary"


def _row(t: Tool) -> str:
    name = f"[{t.name}]({t.url})" if t.url else t.name
    return f"| {name} | {t.org} | {_source(t)} | {t.license} | {t.note} |"


def generate() -> str:
    total = len(TOOLS)
    oss = sum(1 for t in TOOLS if t.open_source)
    categories = sorted({t.category for t in TOOLS}, key=lambda c: c.label)

    by_cat: dict[Category, list[Tool]] = defaultdict(list)
    for t in TOOLS:
        by_cat[t.category].append(t)

    out: list[str] = []
    out.append("<!-- AUTO-GENERATED by report.py — run `python main.py generate` to refresh. -->")
    out.append("# 🧩 AI Agent Skills & Extensions Directory\n")
    out.append(" ".join([
        _badge("version", __version__, "blue"),
        _badge("entries", total, "green"),
        _badge("open%20source", oss, "brightgreen"),
        _badge("categories", len(categories), "purple"),
        "[![CI](https://github.com/Amarel-Taylor-Scott/ai-agent-skills-directory/actions/workflows/ci.yml/badge.svg)]"
        "(https://github.com/Amarel-Taylor-Scott/ai-agent-skills-directory/actions/workflows/ci.yml)",
        "[![License: MIT](https://img.shields.io/badge/License-MIT-yellow.svg)](LICENSE)",
    ]))
    out.append("")
    out.append("> A curated, machine-readable directory of the **skill / extension ecosystems** "
               "that extend what AI agents & assistants can do — open skill/tool protocols, "
               "platform skill systems from the major providers, and skill/agent marketplaces.\n")
    out.append("Distinct from a list of individual tools (see *agent tools*) or code SDKs (see "
               "*agent frameworks*): this catalogs the *systems, protocols, and marketplaces* "
               "themselves. New and fast-moving — curated conservatively.\n")

    out.append("## Quick start\n")
    out.append("```bash")
    out.append("pip install -e .                # stdlib-only; no runtime deps")
    out.append("skill-dir list                  # list all")
    out.append("skill-dir list --open-source    # only open protocols/systems")
    out.append("skill-dir list --category platform_skills")
    out.append("skill-dir search mcp            # search name/org/note/tags")
    out.append("skill-dir export --format csv > skills.csv")
    out.append("skill-dir generate              # regenerate this README")
    out.append("```\n")

    out.append("## At a glance\n")
    out.append(f"- **{total}** entries across **{len(categories)}** categories")
    out.append(f"- 🟢 **{oss}** open · 🔒 **{total - oss}** proprietary\n")

    out.append("## Design and motion resources\n")
    out.append("The [design and motion guide](resources/design-motion.md) introduces the individual skills and tools. "
               "Browse their upstream links, licenses and tags in the [companion CSV](resources/design-motion.csv) "
               "or search it with `skill-dir resources`.\n")
    out.append("```bash")
    out.append("skill-dir resources animation --kind skill")
    out.append("skill-dir resources --kind tool --format json")
    out.append("```\n")

    out.append("The [creative discovery guide](resources/creative-discovery.md) covers places to find more projects. "
               "Browse the [source catalog](resources/creative-discovery.csv) or run `skill-dir sources` to list them all. "
               "Use `skill-dir sources --has-feed --format json` for sources with a feed URL.\n")

    out.append("## Directory\n")
    for cat in sorted(by_cat, key=lambda c: c.label):
        tools = sorted(by_cat[cat], key=lambda t: t.name.lower())
        out.append(f"### {cat.label} ({len(tools)})\n")
        out.append("| Name | Org | Source | License | Notes |")
        out.append("|------|-----|--------|---------|-------|")
        out.extend(_row(t) for t in tools)
        out.append("")

    out.append("## Legend\n")
    out.append("🟢 open source / open standard · 🔃 source-available · 🔒 proprietary / hosted.\n")

    out.append("## Contributing\n")
    out.append("Add or correct an entry in [`data.py`](data.py), run `python main.py generate`, "
               "and open a PR. See [CONTRIBUTING.md](CONTRIBUTING.md) and "
               "[CODE_OF_CONDUCT.md](CODE_OF_CONDUCT.md). Catalog skill *systems/protocols/"
               "marketplaces* (not individual tools); link the canonical page; omit anything you "
               "can't verify.\n")

    out.append("## License\n")
    out.append("[MIT](LICENSE) © Amarel Taylor Scott. Catalog metadata only; each platform's own "
               "license/terms govern its use.\n")
    return "\n".join(out)


if __name__ == "__main__":
    print(generate())
